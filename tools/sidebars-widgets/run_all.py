"""Run every item test, write results, update manifest status, catalog.json, CATALOG.md and COUNTS.md.

  python run_all.py            run all items (4 in parallel)
  python run_all.py --only a,b run named items only
  python run_all.py --no-write test only, leave manifests alone
Stdlib only. Chrome or Edge is found automatically (SC_CHROME overrides).
"""
import json, subprocess, sys, time
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "_lib"))
import harness  # noqa: E402


def items():
    out = []
    for kind in ("sidebars", "widgets"):
        for d in sorted((ROOT / kind).glob("*/manifest.json")):
            out.append(d.parent)
    return out


def run_one(d):
    t = time.time()
    p = subprocess.run([sys.executable, "test.py"], cwd=str(d), capture_output=True, text=True, encoding="utf-8", errors="replace")
    return d, p.returncode, p.stdout.strip(), round(time.time() - t, 1)


def main():
    args = sys.argv[1:]
    only = None
    if "--only" in args:
        only = set(args[args.index("--only") + 1].split(","))
    write = "--no-write" not in args
    sel = [d for d in items() if not only or d.name in only]
    chrome = harness.find_chrome()
    print("items: %d  browser: %s" % (len(sel), chrome or "none (static checks only)"))
    with ThreadPoolExecutor(max_workers=4) as ex:
        results = list(ex.map(run_one, sel))
    now = datetime.now().astimezone().strftime("%Y-%m-%d %H:%M %Z")
    for d, rc, out, secs in results:
        print(out)
    if not write:
        return
    cat = []
    for d in items():
        res_file = ROOT / "results" / (d.name + ".json")
        m = json.loads((d / "manifest.json").read_text(encoding="utf-8"))
        r = json.loads(res_file.read_text(encoding="utf-8")) if res_file.exists() else None
        if r and (not only or d.name in only):
            m["status"] = r["status"]
            m["last_tested"] = now
            m["checks"] = {"passed": r["passed"], "failed": r["failed"], "total": r["total"]}
            m["bytes"] = r["extra"].get("bytes"); m["gzip_bytes"] = r["extra"].get("gzip_bytes")
            if r["status"] == "pass":
                m["verified_in"] = ["headless Chrome/Edge at 360 px and 1280 px", "OceanWP-like context (root 62.5%)", "GeneratePress-like context"]
            else:
                m["verified_in"] = []
            (d / "manifest.json").write_text(json.dumps(m, indent=1), encoding="utf-8")
        cat.append({"slug": m["slug"], "name": m["name"], "kind": m["kind"], "path": "%s/%s" % (d.parent.name, d.name), "purpose": m["purpose"],
                    "tags": m.get("tags", []), "status": m["status"], "bytes": m.get("bytes"), "gzip_bytes": m.get("gzip_bytes"),
                    "files": m["files"], "test_command": m["test_command"], "last_tested": m.get("last_tested")})
    (ROOT / "catalog.json").write_text(json.dumps({"slice": "sidebars-widgets", "generated": now, "items": cat}, indent=1), encoding="utf-8")
    lines = ["# Catalog: sidebars and widgets", "", "Generated by run_all.py on %s. Status comes from the last test run." % now, "",
             "| Item | Kind | Status | Bytes (gzip) | Purpose |", "|---|---|---|---|---|"]
    for c in cat:
        lines.append("| [%s](%s/manifest.json) | %s | %s | %s (%s) | %s |" % (c["slug"], c["path"], c["kind"], c["status"], c["bytes"], c["gzip_bytes"], c["purpose"].replace("|", "/")))
    (ROOT / "CATALOG.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    n = len(cat)
    cnt = {s: sum(1 for c in cat if c["status"] == s) for s in ("pass", "fail", "static-only", "untested")}
    k = {kk: sum(1 for c in cat if c["kind"] == kk) for kk in ("sidebar", "widget")}
    fails = [c["slug"] for c in cat if c["status"] == "fail"]
    lines = ["# COUNTS", "", "Updated %s by run_all.py." % now, "",
             "| Measure | Count |", "|---|---|",
             "| Items built | %d (%d sidebar layouts, %d widgets) |" % (n, k["sidebar"], k["widget"]),
             "| Tested, pass (static and browser) | %d |" % cnt["pass"],
             "| Tested, fail | %d |" % cnt["fail"],
             "| Static checks only, no browser run | %d |" % cnt["static-only"],
             "| Not yet tested | %d |" % cnt["untested"], ""]
    if fails:
        lines += ["Failed items: " + ", ".join(fails), ""]
    lines += ["A pass means every check passed: manifest, tokens, HTML, CSS and JS lint, secret scan, size budget, then headless Chrome at 360 px and 1280 px in two theme-like contexts (tap targets 44 px, text 16 px and 18 px floors, 4.5:1 contrast, no horizontal overflow, scripted behavior).",
              "The contexts are approximations written for these tests. No item has run on a real OceanWP or GeneratePress install yet.", ""]
    (ROOT / "COUNTS.md").write_text("\n".join(lines), encoding="utf-8")
    print("built %d  pass %d  fail %d  static-only %d  untested %d" % (n, cnt["pass"], cnt["fail"], cnt["static-only"], cnt["untested"]))
    sys.exit(1 if cnt["fail"] else 0)


if __name__ == "__main__":
    main()
